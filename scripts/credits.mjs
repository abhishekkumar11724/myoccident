#!/usr/bin/env node
/** Generates CREDITS.md from every theme's meta.ts `credits` array.  npm run credits */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const order = fs.readFileSync(path.join(ROOT, 'src/themes/order.ts'), 'utf8');
const names = Object.fromEntries([...order.matchAll(/\{ id: '([^']+)',\s+name: '([^']+)'/g)].map((m) => [m[1], m[2]]));
let md = `# Credits & licences\n\nGenerated by \`npm run credits\` from each theme's \`meta.ts\`. Only CC0 / public-domain / OFL / MIT / Apache assets are used, all self-hosted.\n\n## Project\n- Photos: the author's own (from his phone / Instagram archive); friends and family pictured agreed to appear.\n- [Astro](https://astro.build) (MIT), [sharp](https://sharp.pixelplumbing.com) (Apache-2.0), [Playwright](https://playwright.dev) (Apache-2.0, dev only).\n- Image treatments: original code in \`scripts/fx\`.\n\n## Themes\n`;
let total = 0;
for (const id of Object.keys(names)) {
  const f = path.join(ROOT, 'src/themes', id, 'meta.ts');
  if (!fs.existsSync(f)) continue;
  const meta = (await import(pathToFileURL(f).href)).default;
  md += `\n### ${names[id]} (\`${id}\`)\n`;
  if (!meta.credits?.length) md += '- Nothing third-party: all original code, SVG and CSS.\n';
  for (const c of meta.credits ?? []) { total++; md += `- **${c.name}** - ${c.kind}, ${c.license}${c.note ? ` (${c.note})` : ''}${c.url ? ` - ${c.url}` : ''}\n`; }
}
fs.writeFileSync(path.join(ROOT, 'CREDITS.md'), md);
console.log(`CREDITS.md written (${total} third-party entries)`);
